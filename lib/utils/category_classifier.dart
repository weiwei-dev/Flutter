  /// 获取品类所属大类
  static String getGroup(String category) {
    // 直接匹配
    if (_categoryToGroup.containsKey(category)) {
      return _categoryToGroup[category]!;
    }

    // 模糊匹配：检查品类名称是否包含关键字
    for (var entry in _categoryToGroup.entries) {
      if (category.contains(entry.key)) {
        return entry.value;
      }
    }

    // 反向匹配：检查关键字是否包含品类
    for (var entry in _categoryToGroup.entries) {
      if (entry.key.contains(category) && category.length >= 2) {
        return entry.value;
      }
    }

    return '其他';
  }

  /// 获取大类下的所有品类
  static List<String> getCategoriesInGroup(String group) {
    return _categoryToGroup.entries
        .where((entry) => entry.value == group)
        .map((entry) => entry.key)
        .toList();
  }

  /// 检查是否为已知品类
  static bool isKnownCategory(String category) {
    return _categoryToGroup.containsKey(category);
  }

  /// 添加自定义映射
  static void addMapping(String category, String group) {
    _categoryToGroup[category] = group;
  }

  /// 获取品类统计信息
  static Map<String, dynamic> getCategoryInfo(String category) {
    final group = getGroup(category);
    final isKnown = isKnownCategory(category);

    return {
      'category': category,
      'group': group,
      'isKnown': isKnown,
      'knownCategoriesCount': _categoryToGroup.length,
    };
  }
